#!/usr/bin/env node
// Renders STATUS.md from status/status.yaml plus facts read from the repo.
// `--check` fails when the committed STATUS.md differs from the rendered output.
// Output depends only on files in the working tree, so CI can verify it on a PR branch.

import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { parse } from 'yaml';

export const STATES = ['done', 'in-progress', 'planned', 'blocked', 'deferred'];

const HEADER =
  '<!-- Generated by `pnpm status:generate` from status/status.yaml. Do not edit. -->';

function fail(message) {
  throw new Error(message);
}

function readText(root, path) {
  const full = join(root, path);
  if (!existsSync(full)) fail(`${path} not found`);
  return readFileSync(full, 'utf8');
}

function validateWorkstream(root, workstream, index, seen) {
  const at = `status/status.yaml workstreams[${index}]`;
  if (typeof workstream !== 'object' || workstream === null)
    fail(`${at} must be a mapping`);
  for (const key of ['id', 'name', 'summary']) {
    if (typeof workstream[key] !== 'string' || !workstream[key].trim()) {
      fail(`${at} needs a non-empty ${key}`);
    }
  }
  if (!STATES.includes(workstream.state)) {
    fail(
      `${at} (${workstream.id}) has state "${workstream.state}"; use one of ${STATES.join(', ')}`,
    );
  }
  if (seen.has(workstream.id))
    fail(`${at} has a duplicate id "${workstream.id}"`);
  seen.add(workstream.id);
  if (workstream.state === 'blocked' && !workstream.blockedBy) {
    fail(`${at} (${workstream.id}) is blocked and needs blockedBy`);
  }
  if (workstream.links !== undefined && !Array.isArray(workstream.links)) {
    fail(`${at} (${workstream.id}) links must be a list of repo paths`);
  }
  for (const link of workstream.links ?? []) {
    validateLink(root, `${at} (${workstream.id})`, String(link));
  }
}

// Same slug rule as GitHub: lowercase, drop punctuation, spaces to hyphens,
// repeated headings get -1, -2, ...
function headingSlugs(markdown) {
  const seen = new Map();
  const slugs = new Set();
  for (const line of markdown.split('\n')) {
    const heading = line.match(/^#{1,6}\s+(.+?)\s*#*\s*$/)?.[1];
    if (!heading) continue;
    const base = heading
      .toLowerCase()
      .replace(/[^\p{L}\p{N}\s_-]/gu, '')
      .trim()
      .replaceAll(' ', '-');
    const count = seen.get(base) ?? 0;
    seen.set(base, count + 1);
    slugs.add(count === 0 ? base : `${base}-${count}`);
  }
  return slugs;
}

function validateLink(root, at, link) {
  const hash = link.indexOf('#');
  const target = hash === -1 ? link : link.slice(0, hash);
  if (!existsSync(join(root, target))) {
    fail(`${at} links to ${target}, which does not exist`);
  }
  if (hash === -1 || !target.endsWith('.md')) return;
  const anchor = link.slice(hash + 1);
  if (!headingSlugs(readFileSync(join(root, target), 'utf8')).has(anchor)) {
    fail(
      `${at} links to ${target}#${anchor}, but ${target} has no such heading`,
    );
  }
}

export function loadStatus(root) {
  const data = parse(readText(root, 'status/status.yaml'));
  if (typeof data?.focus !== 'string' || !data.focus.trim()) {
    fail('status/status.yaml needs a focus line');
  }
  if (!Array.isArray(data.workstreams))
    fail('status/status.yaml workstreams must be a list');
  const seen = new Set();
  data.workstreams.forEach((w, i) => validateWorkstream(root, w, i, seen));
  return {
    focus: data.focus.trim(),
    workstreams: data.workstreams.map((w) => ({ ...w, links: w.links ?? [] })),
  };
}

function findProjectFiles(root, dir) {
  const full = join(root, dir);
  if (!existsSync(full)) return [];
  return readdirSync(full, { withFileTypes: true }).flatMap((entry) => {
    if (entry.name === 'node_modules') return [];
    const path = `${dir}/${entry.name}`;
    if (entry.isDirectory()) return findProjectFiles(root, path);
    return entry.name === 'project.json' ? [path] : [];
  });
}

export function collectProjects(root) {
  return ['apps', 'libs']
    .flatMap((dir) => findProjectFiles(root, dir))
    .map((file) => {
      const project = JSON.parse(readFileSync(join(root, file), 'utf8'));
      return {
        name: project.name,
        path: dirname(file),
        type: project.projectType ?? 'unknown',
        tags: project.tags ?? [],
      };
    })
    .sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));
}

function readDoc(root, path) {
  const lines = readFileSync(join(root, path), 'utf8').split('\n').slice(0, 20);
  const field = (name) =>
    lines
      .find((l) => l.startsWith(`${name}:`))
      ?.slice(name.length + 1)
      .trim();
  const text = field('Status');
  const status = (text?.match(/^(.*?\.)(?:\s|$)/)?.[1] ?? text)?.replace(
    /\.$/,
    '',
  );
  return {
    title:
      lines
        .find((l) => /^# /.test(l))
        ?.slice(2)
        .trim() ?? basename(path, '.md'),
    path,
    status,
    updated: field('Updated'),
  };
}

function listDocs(root, dir) {
  const full = join(root, dir);
  if (!existsSync(full)) return [];
  return readdirSync(full)
    .filter((name) => name.endsWith('.md'))
    .sort()
    .map((name) => readDoc(root, `${dir}/${name}`));
}

export function collectDocs(root) {
  return {
    plans: listDocs(root, 'docs/plans'),
    prd: listDocs(root, 'docs/prd'),
    decisions: listDocs(root, 'docs/decisions'),
  };
}

function tableCells(line) {
  return line
    .split(/(?<!\\)\|/)
    .slice(1, -1)
    .map((cell) => cell.trim().replaceAll('\\|', '|'));
}

export function collectOpenQuestions(root) {
  const lines = readText(root, 'Architecture.md').split('\n');
  const start = lines.findIndex((l) =>
    /^##\s+(\d+\.\s*)?Open questions/i.test(l),
  );
  if (start === -1) fail('Architecture.md has no "Open questions" section');
  const rows = [];
  for (const line of lines.slice(start + 1)) {
    if (line.startsWith('## ')) break;
    if (!line.startsWith('|')) continue;
    const cells = tableCells(line);
    if (cells.every((c) => /^:?-+:?$/.test(c)) || cells[0] === '#') continue;
    if (cells.length < 3) {
      fail(`Architecture.md open questions has a malformed row: ${line}`);
    }
    const [id, question, blocks] = cells;
    if (question.startsWith('~~')) continue;
    rows.push({ id, question, blocks });
  }
  return rows;
}

const cell = (value) =>
  String(value ?? '').trim()
    ? String(value)
        .replaceAll('|', '\\|')
        .replace(/\s*\n\s*/g, ' ')
        .trim()
    : '-';

function table(headers, rows) {
  if (rows.length === 0) return ['None.'];
  return [
    `| ${headers.join(' | ')} |`,
    `|${headers.map(() => '---').join('|')}|`,
    ...rows.map((row) => `| ${row.map(cell).join(' | ')} |`),
  ];
}

const link = (label, path) => `[${label}](${path})`;

function docRows(docs) {
  return docs.map((d) => [link(d.title, d.path), d.status, d.updated]);
}

export function render({ status, projects, docs, questions }) {
  const lines = [
    HEADER,
    '',
    '# Project status',
    '',
    `**Focus:** ${status.focus}`,
    '',
    'Edit `status/status.yaml` to change the workstreams. Run `pnpm status:generate` and commit `STATUS.md` with your change; CI fails when it is stale.',
    '',
    '## Workstreams',
    '',
    ...table(
      ['Workstream', 'State', 'Owner', 'Next', 'Summary', 'Links'],
      status.workstreams.map((w) => [
        w.name,
        w.state,
        w.owner,
        w.state === 'blocked'
          ? `Blocked: ${w.blockedBy}${w.next ? `. Next: ${w.next}` : ''}`
          : w.next,
        w.summary,
        w.links
          .map((l) => link(basename(l.split('#')[0], '.md'), l))
          .join(', '),
      ]),
    ),
    '',
    '## Open questions',
    '',
    'From the Open questions section of [Architecture.md](Architecture.md). Answer one there and it leaves this list.',
    '',
    ...table(
      ['#', 'Question', 'Blocks'],
      questions.map((q) => [q.id, q.question, q.blocks]),
    ),
    '',
    '## Documents',
    '',
    'Technical decisions: see the Decisions section of [Architecture.md](Architecture.md).',
    '',
    '### Plans',
    '',
    ...table(['Document', 'Status', 'Updated'], docRows(docs.plans)),
    '',
    '### Product requirements',
    '',
    ...table(['Document', 'Status', 'Updated'], docRows(docs.prd)),
    '',
    '### Product decisions',
    '',
    ...table(['Document', 'Status', 'Updated'], docRows(docs.decisions)),
    '',
    '## Projects',
    '',
    ...table(
      ['Project', 'Type', 'Tags', 'Path'],
      projects.map((p) => [p.name, p.type, p.tags.join(', '), `\`${p.path}\``]),
    ),
    '',
  ];
  return lines.join('\n');
}

export function generate(root) {
  return render({
    status: loadStatus(root),
    projects: collectProjects(root),
    docs: collectDocs(root),
    questions: collectOpenQuestions(root),
  });
}

export function main(argv, root) {
  const target = join(root, 'STATUS.md');
  try {
    const expected = generate(root);
    if (argv.includes('--check')) {
      const current = existsSync(target) ? readFileSync(target, 'utf8') : null;
      if (current === expected) return 0;
      console.error(
        `${relative(process.cwd(), target) || 'STATUS.md'} is ${current === null ? 'missing' : 'out of date'}. Run \`pnpm status:generate\` and commit the result.`,
      );
      return 1;
    }
    writeFileSync(target, expected);
    console.log('Wrote STATUS.md');
    return 0;
  } catch (error) {
    console.error(error.message);
    return 1;
  }
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(process.argv[1]).href
) {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
  process.exit(main(process.argv.slice(2), root));
}
